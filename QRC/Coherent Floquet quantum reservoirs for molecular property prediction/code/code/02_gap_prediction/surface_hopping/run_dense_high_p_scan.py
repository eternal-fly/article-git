#!/usr/bin/env python3
"""Sequential CPU evaluation of the p=0.50,...,1.00 formal-grid subset.

The complete formal protocol is generated by ``run_uniform_p_scan.py``.
Existing shard pairs are reused.
"""

from __future__ import annotations

import time

import numpy as np

from a01_core import load_config
from evaluate_strict_axes import evaluate_shard


HIGH_P_UNIFORM_GRID = tuple(float(value) for value in np.linspace(0.5, 1.0, 11))
READOUTS = ("final", "tm3")


def main() -> None:
    cfg = load_config()
    missing = [
        p for p in HIGH_P_UNIFORM_GRID
        if not any(np.isclose(p, configured) for configured in cfg.p_grid)
    ]
    if missing:
        raise RuntimeError(f"uniform high-p values missing from config: {missing}")

    jobs = [
        (int(seed), float(p), readout)
        for seed in cfg.seeds
        for p in HIGH_P_UNIFORM_GRID
        for readout in READOUTS
    ]
    started = time.time()
    for index, (seed, p, readout) in enumerate(jobs, start=1):
        shard_start = time.time()
        csv_path, npz_path = evaluate_shard("qrc", seed, p, readout)
        print(
            f"[dense-high-p {index:03d}/{len(jobs):03d}] "
            f"seed={seed} p={p:.2f} readout={readout} "
            f"elapsed={time.time() - shard_start:.1f}s "
            f"csv={csv_path.name} npz={npz_path.name}",
            flush=True,
        )
    print(
        f"dense high-p scan complete: {len(jobs)} fixed shards, "
        f"elapsed={time.time() - started:.1f}s",
        flush=True,
    )


if __name__ == "__main__":
    main()
